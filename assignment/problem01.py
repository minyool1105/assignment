"""
8세 미만: 무료 (0원)
8세 이상 ~ 19세 이하 (청소년): 10,000원
20세 이상 ~ 64세 이하 (성인): 20,000원
65세 이상 (경로): 5,000원
"""

a = int(input("나이를 입력하세요 : "))
if a<8:
    print("무료입니다.")
elif a>=8 and a <= 19:
    print("입장료는 10,000원입니다.")
elif a >= 20 and a <= 64:
    print("입장료는 20,000원입니다.")
elif a>= 65:
    print("입장료는 5,000원입니다.")